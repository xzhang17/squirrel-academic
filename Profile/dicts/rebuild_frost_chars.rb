#!/usr/bin/ruby
# Generate the ordinary character dictionary while preserving Ice's readings.
require 'digest'
require 'json'
require 'yaml'
require 'tempfile'

revision = '3ba4f1df224823079b947ce1553441c36097b124'
blob = '9cbfe2acf59bb3124993d4b8b3b271f8e246b72d'
abort 'Usage: ruby rebuild_frost_chars.rb /path/to/Frost/cn_dicts/8105.dict.yaml' unless ARGV.length == 1
raw = File.binread(ARGV.first)
abort 'Frost dictionary does not match the pinned revision.' unless Digest::SHA1.hexdigest("blob #{raw.bytesize}\0" + raw) == blob

dir = File.join(__dir__, 'cn_dicts')
ice = File.read(File.join(dir, '8105.dict.yaml'), encoding: 'UTF-8')
def split_dictionary(text)
  header, marker, rows = text.partition(/^\.\.\.\r?\n/)
  raise 'Missing Rime dictionary header' if marker.empty?
  [header, rows]
end

def entries(rows)
  rows.each_line.with_object({}) do |line, scores|
    next if line.strip.empty? || line.start_with?('#')
    word, code, weight, *rest = line.chomp.split("\t", -1)
    raise "Invalid character entry: #{line.chomp}" unless rest.empty? && word.to_s.length == 1 &&
        code&.match?(/\A[a-z]+\z/) && weight&.match?(/\A\d+\z/)
    key = [word, code]
    raise "Duplicate character and reading: #{key.join(' ')}" if scores.key?(key)
    scores[key] = Integer(weight, 10)
  end
end

ice_header, ice_rows = split_dictionary(ice)
original = entries(ice_rows)
_, frost_rows = split_dictionary(raw.force_encoding('UTF-8'))
frost = entries(frost_rows)
shared = original.keys & frost.keys
ice_mass = shared.sum { |key| original.fetch(key) }
frost_mass = shared.sum { |key| frost.fetch(key) }
raise 'Missing shared weight mass' unless ice_mass.positive? && frost_mass.positive?

# Versions are labels: an unquoted 1.10 must keep its trailing zero.
metadata = YAML.parse(ice_header).root
field = metadata.children.each_slice(2).find { |key, _| key.value == 'version' } if metadata.is_a?(Psych::Nodes::Mapping)
version = field && field.last
raise 'Expected a nonempty dictionary version' unless version.is_a?(Psych::Nodes::Scalar) && !version.value.to_s.strip.empty?
generated_version = JSON.generate("#{version.value}.frost-#{revision[0, 7]}")
output = <<~HEADER
  # encoding: utf-8
  # Generated by dicts/rebuild_frost_chars.rb for ordinary Zenfire Pinyin.
  # Readings and order: dicts/cn_dicts/8105.dict.yaml (https://github.com/iDvel/rime-ice).
  # Shared scores: https://github.com/gaboolic/rime-frost/blob/#{revision}/cn_dicts/8105.dict.yaml
  # Other readings use scaled Ice weights, including adaptations from SUBTLEX-CH,
  # © 2010 Qing Cai and Marc Brysbaert (Creative Commons Attribution), https://doi.org/10.1371/journal.pone.0010729.s002
  ---
  name: zenfire_chars
  version: #{generated_version}
  sort: by_weight
  ...
HEADER
ice_rows.each_line do |line|
  if line.strip.empty? || line.start_with?('#')
    output << line
    next
  end
  word, code, old = line.chomp.split("\t")
  score = frost.fetch([word, code]) do
    # Round half up; keep a positive incidental reading eligible.
    weight = Integer(old, 10)
    weight.zero? ? 0 : [1, (2 * weight * frost_mass + ice_mass) / (2 * ice_mass)].max
  end
  output << "#{word}\t#{code}\t#{score}\n"
end

target = File.join(dir, 'zenfire_chars.dict.yaml')
unless File.exist?(target) && File.binread(target) == output.b
  Tempfile.create(['.zenfire-chars-', '.yaml'], dir) do |file|
    file.binmode
    file.write(output)
    file.close
    File.rename(file.path, target)
  end
end
puts "#{original.size} character readings; #{shared.size} shared Frost scores."
